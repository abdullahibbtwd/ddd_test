export const ErrorCodeSchema = z.enum([
  ErrorCode.VALIDATION_FAILED,
  ErrorCode.UNAUTHENTICATED,
  ErrorCode.FORBIDDEN,
  ErrorCode.NOT_FOUND,
  ErrorCode.CONFLICT,
  ErrorCode.DUPLICATE_EIK,
  ErrorCode.INVALID_EIK,
  ErrorCode.CLIENT_ARCHIVED,
  ErrorCode.CLIENT_HAS_ACTIVE_SITES,
  ErrorCode.SUBSCRIPTION_OVERLAP,
  ErrorCode.SITE_TERMINATED,
  ErrorCode.VISIT_DATE_OUT_OF_WINDOW,
  ErrorCode.VISIT_EDIT_WINDOW_EXPIRED,
  ErrorCode.VISIT_NOT_OWNER,
  ErrorCode.VISIT_ALREADY_CANCELLED,
  ErrorCode.IDEMPOTENCY_KEY_REUSED_WITH_DIFFERENT_BODY,
  ErrorCode.SITE_OUT_OF_SCOPE,
  ErrorCode.TOO_MANY_REQUESTS,
  ErrorCode.ACCOUNT_LOCKED,
  ErrorCode.PASSWORD_CHANGE_REQUIRED,
  ErrorCode.LAST_ADMIN_REQUIRED,
  ErrorCode.SELF_MODIFICATION_FORBIDDEN,
  ErrorCode.INTERNAL,
]);

export type ErrorCode = z.infer<typeof ErrorCodeSchema>;

export const ApiErrorSchema = z.object({
  code: ErrorCodeSchema,
  message: z.string(),
  details: z.unknown().optional(),
});

export type ApiError = z.infer<typeof ApiErrorSchema>;
