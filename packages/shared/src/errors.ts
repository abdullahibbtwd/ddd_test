  SITE_TERMINATED: "SITE_TERMINATED",
  VISIT_DATE_OUT_OF_WINDOW: "VISIT_DATE_OUT_OF_WINDOW",
  VISIT_EDIT_WINDOW_EXPIRED: "VISIT_EDIT_WINDOW_EXPIRED",
